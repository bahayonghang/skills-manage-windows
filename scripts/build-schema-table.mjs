#!/usr/bin/env node
// scripts/build-schema-table.mjs
//
// 扫描 src-tauri/src/db/schema/*.rs 中的 CREATE TABLE / CREATE INDEX 语句，
// 抽取表名 / 字段 / 类型 / 默认值 / 主键 / 索引，
// 生成 docs/architecture/_generated/data-model.md。
// 在 docs:gen 中调用，配合改 schema 后一并刷新文档。

import { readdirSync, readFileSync, mkdirSync, writeFileSync } from 'node:fs'
import { join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = fileURLToPath(new URL('.', import.meta.url))
const repoRoot = join(__dirname, '..')
const schemaDir = join(repoRoot, 'src-tauri', 'src', 'db', 'schema')
const outDir = join(repoRoot, 'docs', 'architecture', '_generated')
const outFile = join(outDir, 'data-model.md')

const TABLE_RE = /CREATE TABLE IF NOT EXISTS\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*\(([\s\S]*?)\)\s*"/g
const INDEX_RE = /CREATE INDEX IF NOT EXISTS\s+([a-zA-Z_][a-zA-Z0-9_]*)\s+ON\s+([a-zA-Z_][a-zA-Z0-9_]*)\s*\(([^)]+)\)/g

function shortPath(absolute) {
  return relative(repoRoot, absolute).split(sep).join('/')
}

function parseColumns(body) {
  const parts = []
  let depth = 0
  let buf = ''
  for (const ch of body) {
    if (ch === '(') depth++
    if (ch === ')') depth--
    if (ch === ',' && depth === 0) {
      parts.push(buf)
      buf = ''
    } else {
      buf += ch
    }
  }
  if (buf.length) parts.push(buf)

  const cols = []
  let pkComposite = null
  for (const raw of parts) {
    const trimmed = raw.trim().replace(/\s+/g, ' ')
    if (!trimmed) continue
    if (/^PRIMARY KEY\b/i.test(trimmed)) {
      pkComposite = trimmed
        .replace(/^PRIMARY KEY\s*\(/i, '')
        .replace(/\)$/, '')
        .split(',')
        .map((s) => s.trim())
      continue
    }
    if (/^FOREIGN KEY\b/i.test(trimmed)) continue
    const tokens = trimmed.split(/\s+/)
    const name = tokens.shift()
    const rest = tokens.join(' ')
    cols.push({
      name,
      type: rest
        .replace(/PRIMARY KEY/i, '')
        .replace(/NOT NULL/i, '')
        .replace(/DEFAULT [^,]+/i, '')
        .trim(),
      notNull: /NOT NULL/i.test(rest),
      defaultExpr: extractDefault(rest),
      isPk: /PRIMARY KEY/i.test(rest),
    })
  }
  if (pkComposite) {
    for (const col of cols) {
      if (pkComposite.includes(col.name)) col.isPk = true
    }
  }
  return cols
}

function extractDefault(text) {
  const m = text.match(/DEFAULT\s+([^,]+?)(?:\s+NOT NULL)?$/i)
  if (!m) return null
  return m[1].trim()
}

function parseFile(filePath) {
  const text = readFileSync(filePath, 'utf8')
  const tables = []
  let m
  while ((m = TABLE_RE.exec(text)) !== null) {
    tables.push({ name: m[1], cols: parseColumns(m[2]), indexes: [] })
  }
  INDEX_RE.lastIndex = 0
  let idx
  while ((idx = INDEX_RE.exec(text)) !== null) {
    const target = tables.find((t) => t.name === idx[2])
    if (!target) continue
    target.indexes.push({
      name: idx[1],
      columns: idx[3].split(',').map((s) => s.trim()),
    })
  }
  return { source: shortPath(filePath), tables }
}

function escapePipe(text) {
  return String(text || '').replace(/\|/g, '\\|')
}

function render(modules) {
  const totalTables = modules.reduce((acc, m) => acc + m.tables.length, 0)
  const out = []
  out.push('<!-- AUTOGENERATED — do not edit by hand. -->')
  out.push('<!-- regenerate via: pnpm docs:gen -->')
  out.push('')
  out.push(`> Schema modules: ${modules.length}　·　Tables: ${totalTables}`)
  out.push('')
  for (const mod of modules) {
    out.push(`## \`${mod.source}\``)
    out.push('')
    for (const table of mod.tables) {
      out.push(`### \`${table.name}\``)
      out.push('')
      out.push('| Column | Type | Nullable | Default | PK |')
      out.push('| --- | --- | --- | --- | --- |')
      for (const col of table.cols) {
        out.push(
          `| \`${col.name}\` | \`${escapePipe(col.type)}\` | ${col.notNull ? 'no' : 'yes'} | ${
            col.defaultExpr ? `\`${escapePipe(col.defaultExpr)}\`` : '—'
          } | ${col.isPk ? '✓' : '—'} |`
        )
      }
      out.push('')
      if (table.indexes.length) {
        out.push('Indexes:')
        for (const ix of table.indexes) {
          out.push(`- \`${ix.name}\` on \`(${ix.columns.join(', ')})\``)
        }
        out.push('')
      }
    }
  }
  out.push('---')
  out.push('Last generated: ' + new Date().toISOString().slice(0, 10))
  out.push('')
  return out.join('\n')
}

function main() {
  const files = readdirSync(schemaDir)
    .filter((f) => f.endsWith('.rs') && f !== 'mod.rs')
    .map((f) => join(schemaDir, f))
  const modules = files.map(parseFile).filter((m) => m.tables.length > 0)
  if (!modules.length) {
    console.error('[build-schema-table] no CREATE TABLE statements found — refusing to overwrite')
    process.exit(1)
  }
  const md = render(modules)
  mkdirSync(outDir, { recursive: true })
  writeFileSync(outFile, md, 'utf8')
  const total = modules.reduce((a, m) => a + m.tables.length, 0)
  console.log(`[build-schema-table] wrote ${total} tables → ${shortPath(outFile)}`)
}

main()
